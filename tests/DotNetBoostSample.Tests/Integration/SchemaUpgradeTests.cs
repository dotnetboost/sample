using Npgsql;
using Xunit;

namespace DotNetBoostSample.Tests.Integration;

/// <summary>
/// A database made before Category and Product took their ids from HiLo sequences still works:
/// the initialiser adds the sequences, starting past the rows already there.
///
/// <para><b>Why this is a test and not a note.</b> Aspire keeps the sample's PostgreSQL on a data
/// volume across runs, and <c>EnsureCreated</c> does nothing to a database that exists — so every
/// volume made before this change has identity columns and no sequences. Without the upgrade the
/// first create on it fails, because the sequence EF asks for a block of ids does not exist; with
/// an upgrade that started the sequences at 1, it fails a different way, because the first ids
/// handed out are rows the table already has. Each fixture starts from a fresh container, so
/// nothing else in the suite ever sees an old database.</para>
///
/// <para>The old database is made rather than kept: the application is booted once on an empty
/// database, which creates and seeds it, and then the sequences are dropped and the identity
/// columns put back — the schema an older build would have left behind, rows included.</para>
/// </summary>
[Collection(SampleAppCollection.Name)]
public sealed class SchemaUpgradeTests(SampleApp app)
{
    [RequiresDockerFact]
    public async Task A_database_from_before_the_HiLo_keys_gets_its_sequences_past_the_existing_ids()
    {
        var database = $"upgrade_{Guid.NewGuid():N}"[..20];
        await app.ScalarAsync($"CREATE DATABASE \"{database}\"");

        var connectionString = app.ConnectionStringFor(database);

        // Created and seeded by the current build.
        await using (var current = app.Boot(connectionString))
            current.CreateClient();

        // Turned back into what an older build left: identity columns, no sequences, and the rows.
        await ExecuteAsync(connectionString, """
            DROP SEQUENCE "CategoryIds";
            DROP SEQUENCE "ProductIds";
            ALTER TABLE "Categories" ALTER COLUMN "Id" ADD GENERATED BY DEFAULT AS IDENTITY;
            ALTER TABLE "Products" ALTER COLUMN "Id" ADD GENERATED BY DEFAULT AS IDENTITY;
            """);

        var highestProduct = int.Parse(await ScalarAsync(connectionString, """SELECT MAX("Id") FROM "Products" """));
        var highestCategory = int.Parse(await ScalarAsync(connectionString, """SELECT MAX("Id") FROM "Categories" """));

        await using var upgraded = app.Boot(connectionString);
        var client = upgraded.CreateClient().AsActor();

        Assert.Equal("2", await ScalarAsync(connectionString,
            """SELECT COUNT(*) FROM information_schema.sequences WHERE sequence_name IN ('CategoryIds', 'ProductIds')"""));

        var category = (await client.GetJsonAsync("/api/categories"))
            .EnumerateArray().First(c => c.Str("slug") == "furniture").Int("id");

        // The first id handed out is past every existing one, so the insert is not refused.
        var id = await client.CreateProductAsync(category, "Made after the upgrade");

        Assert.True(id > highestProduct, $"Product {id} was given an id at or below {highestProduct}.");
        Assert.Equal(
            "Made after the upgrade",
            (await client.GetJsonAsync($"/api/products/{id}")).GetProperty("translations").GetProperty("en").Str("Name"));

        var created = (await client.SendJsonCheckedAsync(HttpMethod.Post, "/api/categories", new
        {
            slug = $"after-upgrade-{Guid.NewGuid():N}"[..24],
            translations = new Dictionary<string, Dictionary<string, string>>
            {
                ["en"] = new() { ["Name"] = "After the upgrade", ["Description"] = "A new category." }
            }
        })).Int("id");

        Assert.True(created > highestCategory, $"Category {created} was given an id at or below {highestCategory}.");
    }

    private static async Task ExecuteAsync(string connectionString, string sql)
    {
        await using var connection = new NpgsqlConnection(connectionString);
        await connection.OpenAsync();
        await using var command = new NpgsqlCommand(sql, connection);
        await command.ExecuteNonQueryAsync();
    }

    private static async Task<string> ScalarAsync(string connectionString, string sql)
    {
        await using var connection = new NpgsqlConnection(connectionString);
        await connection.OpenAsync();
        await using var command = new NpgsqlCommand(sql, connection);
        return (await command.ExecuteScalarAsync())?.ToString() ?? "";
    }
}
