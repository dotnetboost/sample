using Npgsql;
using Xunit;

namespace DotNetBoostSample.Tests.Integration;

/// <summary>
/// A database made while Category and Product took their ids from HiLo sequences still works: the
/// initialiser gives the key columns their identity back, counting from past the rows already there.
///
/// <para><b>Why this is a test and not a note.</b> Aspire keeps the sample's PostgreSQL on a data
/// volume across runs, and <c>EnsureCreated</c> does nothing to a database that exists. A volume
/// from the HiLo builds is in one of two states, and each fails the first create differently
/// without the upgrade: created by those builds, the key is a plain integer with no default, so the
/// INSERT is refused for a null id; created before them, the key kept its identity but the HiLo
/// builds sent ids it never counted, so it hands out one the table already has. Each fixture starts
/// from a fresh container, so nothing else in the suite ever sees an old database.</para>
///
/// <para>The old database is made rather than kept: the application is booted once on an empty
/// database, which creates and seeds it, and is then turned into what an older build left behind,
/// rows included.</para>
/// </summary>
[Collection(SampleAppCollection.Name)]
public sealed class SchemaUpgradeTests(SampleApp app)
{
    /// <summary>
    /// The ids the HiLo builds handed out, well past where an identity counter on a seeded
    /// database would be.
    /// </summary>
    private const int HiLoId = 1000;

    [RequiresDockerFact]
    public async Task A_database_created_with_HiLo_keys_gets_identity_columns_past_the_existing_ids()
    {
        var connectionString = await SeededDatabaseAsync();

        // What a HiLo build's EnsureCreated left: no identity on either key, the two sequences, and
        // rows with ids from their blocks.
        await ExecuteAsync(connectionString, $"""
            ALTER TABLE "Categories" ALTER COLUMN "Id" DROP IDENTITY;
            ALTER TABLE "Products" ALTER COLUMN "Id" DROP IDENTITY;
            CREATE SEQUENCE "CategoryIds" START WITH 1 INCREMENT BY 10 NO CYCLE;
            CREATE SEQUENCE "ProductIds" START WITH 1 INCREMENT BY 10 NO CYCLE;
            INSERT INTO "Categories" ("Id", "Slug", "CreatedAt") VALUES ({HiLoId}, 'from-the-hilo-builds', now());
            INSERT INTO "Products" ("Id", "Sku", "Price", "CategoryId", "CreatedAt")
                VALUES ({HiLoId}, 'HILO-ERA', 1, {HiLoId}, now());
            """);

        await AssertCreatesArePastAsync(connectionString);

        Assert.Equal("YES,YES", await ScalarAsync(connectionString, """
            SELECT string_agg(is_identity, ',' ORDER BY table_name) FROM information_schema.columns
            WHERE table_name IN ('Categories', 'Products') AND column_name = 'Id'
            """));
    }

    [RequiresDockerFact]
    public async Task A_database_that_kept_its_identity_through_the_HiLo_builds_counts_past_their_ids()
    {
        var connectionString = await SeededDatabaseAsync();

        // Identity columns from before the HiLo builds, and rows those builds then added with ids of
        // their own, which GENERATED BY DEFAULT accepted and the counter never saw.
        await ExecuteAsync(connectionString, $"""
            INSERT INTO "Categories" ("Id", "Slug", "CreatedAt") VALUES ({HiLoId}, 'from-the-hilo-builds', now());
            INSERT INTO "Products" ("Id", "Sku", "Price", "CategoryId", "CreatedAt")
                VALUES ({HiLoId}, 'HILO-ERA', 1, {HiLoId}, now());
            """);

        await AssertCreatesArePastAsync(connectionString);
    }

    /// <summary>A database of its own, created and seeded by the current build.</summary>
    private async Task<string> SeededDatabaseAsync()
    {
        var database = $"upgrade_{Guid.NewGuid():N}"[..20];
        await app.ScalarAsync($"CREATE DATABASE \"{database}\"");

        var connectionString = app.ConnectionStringFor(database);

        await using (var current = app.Boot(connectionString))
            current.CreateClient();

        return connectionString;
    }

    /// <summary>
    /// Boots the current build on the old database and creates a product and a category through
    /// the API: both are accepted, and both ids are past every id the old build handed out.
    /// </summary>
    private async Task AssertCreatesArePastAsync(string connectionString)
    {
        await using var upgraded = app.Boot(connectionString);
        var client = upgraded.CreateClient().AsActor();

        var category = (await client.GetJsonAsync("/api/categories"))
            .EnumerateArray().First(c => c.Str("slug") == "furniture").Int("id");

        var id = await client.CreateProductAsync(category, "Made after the upgrade");

        Assert.True(id > HiLoId, $"Product {id} was given an id at or below {HiLoId}.");
        Assert.Equal(
            "Made after the upgrade",
            (await client.GetJsonAsync($"/api/products/{id}")).GetProperty("translations").GetProperty("en").Str("Name"));

        var created = (await client.SendJsonCheckedAsync(HttpMethod.Post, "/api/categories", new
        {
            slug = $"after-upgrade-{Guid.NewGuid():N}"[..24],
            translations = new Dictionary<string, Dictionary<string, string>>
            {
                ["en"] = new() { ["Name"] = "After the upgrade", ["Description"] = "A new category." }
            }
        })).Int("id");

        Assert.True(created > HiLoId, $"Category {created} was given an id at or below {HiLoId}.");
    }

    private static async Task ExecuteAsync(string connectionString, string sql)
    {
        await using var connection = new NpgsqlConnection(connectionString);
        await connection.OpenAsync();
        await using var command = new NpgsqlCommand(sql, connection);
        await command.ExecuteNonQueryAsync();
    }

    private static async Task<string> ScalarAsync(string connectionString, string sql)
    {
        await using var connection = new NpgsqlConnection(connectionString);
        await connection.OpenAsync();
        await using var command = new NpgsqlCommand(sql, connection);
        return (await command.ExecuteScalarAsync())?.ToString() ?? "";
    }
}
